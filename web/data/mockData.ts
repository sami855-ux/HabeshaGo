import { ParkingLot, ParkingSlot } from "@/types/parking"

const generateMockSlots = (
  lotId: string,
  totalSlots: number,
  availableSlots: number,
): ParkingSlot[] => {
  const slots: ParkingSlot[] = []
  const slotTypes = ["CAR", "MOTORCYCLE", "EV_STANDARD", "EV_FAST"]
  const statuses = ["AVAILABLE", "OCCUPIED", "RESERVED"]

  for (let i = 1; i <= totalSlots; i++) {
    const isAvailable = i <= availableSlots
    slots.push({
      id: `${lotId}-slot-${i}`,
      parkingLotId: lotId,
      slotNumber: `A${i}`,
      slotType: slotTypes[Math.floor(Math.random() * slotTypes.length)] as any,
      status: isAvailable ? "AVAILABLE" : "OCCUPIED",
      isOccupied: !isAvailable,
      floor: Math.floor(Math.random() * 3) + 1,
      section: String.fromCharCode(65 + Math.floor(Math.random() * 5)),
      isEV: i % 3 === 0,
      hasCharger: i % 3 === 0,
      lastOccupiedAt: !isAvailable ? new Date().toISOString() : undefined,
      sensorId: `SENSOR-${i}`,
    })
  }
  return slots
}

